"""Studio recipe index: catalog contract + recorded weights / smoke timings.

Catalog JSON is the source of truth for title, kind, GPU, workflow, and
defaults. ``benchmarks/models.json`` only adds weights, nodes, and runs.
Adding a catalog file without a matching overlay id fails the unit tests.

Regenerate the docs page:

    python3 -m benchmarks --write
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from catalog import ROOT, list_catalogs, load_catalog
from catalog.gates import (
    render_studio_recipe_table,
    render_workflow_exception_table,
    write_workflow_exception_docs,
)
from recipes import render_legacy_profiles_table, write_legacy_profiles_docs

OVERLAY_PATH = ROOT / "benchmarks" / "models.json"
DOCS_PATH = ROOT / "docs" / "guide" / "models.md"
STUDIO_SNIPPET_PATH = ROOT / "docs" / "guide" / "_generated_studio_recipes.md"
WORKFLOW_GATES_PATH = ROOT / "docs" / "guide" / "_generated_workflow_gates.md"
LEGACY_PROFILES_PATH = ROOT / "docs" / "guide" / "_generated_legacy_profiles.md"
SCHEMA = 1
SMOKE_STATUSES = {"recorded", "pending", "hydrated"}
KIND_SECTIONS = (
    ("t2i", "文生图"),
    ("t2v", "文生视频"),
    ("i2v", "图生视频"),
    ("i23d", "图生 3D"),
    ("other", "其他"),
)
GENERATED_BANNER = "<!-- Generated by python3 -m benchmarks --write. Do not edit by hand. -->"


def load_overlay(path: Path | None = None) -> dict[str, Any]:
    payload = json.loads((path or OVERLAY_PATH).read_text(encoding="utf-8"))
    if payload.get("schema") != SCHEMA:
        raise ValueError(f"unsupported models overlay schema: {payload.get('schema')!r}")
    models = payload.get("models")
    if not isinstance(models, list) or not models:
        raise ValueError("benchmarks/models.json needs a non-empty models list")
    seen: set[str] = set()
    for item in models:
        if not isinstance(item, dict) or not str(item.get("id") or "").strip():
            raise ValueError("each overlay model needs an id")
        recipe_id = str(item["id"])
        if recipe_id in seen:
            raise ValueError(f"duplicate overlay id: {recipe_id}")
        seen.add(recipe_id)
        smoke = item.get("smoke") if isinstance(item.get("smoke"), dict) else {}
        status = str(smoke.get("status") or "pending")
        if status not in SMOKE_STATUSES:
            raise ValueError(f"overlay {recipe_id} has unknown smoke.status {status!r}")
        gpu = str(smoke.get("gpu") or "")
        if gpu == "T4":
            raise ValueError(f"overlay {recipe_id} must not record T4")
    payload["models"] = models
    return payload


def overlay_by_id(overlay: dict[str, Any] | None = None) -> dict[str, dict[str, Any]]:
    payload = overlay if overlay is not None else load_overlay()
    return {str(item["id"]): item for item in payload["models"]}


def merged_models(overlay: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    payload = overlay if overlay is not None else load_overlay()
    extra = overlay_by_id(payload)
    rows: list[dict[str, Any]] = []
    for item in list_catalogs():
        catalog = load_catalog(item["id"])
        overlay_row = extra.get(item["id"])
        if overlay_row is None:
            raise ValueError(f"catalog {item['id']!r} is missing from benchmarks/models.json")
        defaults = {
            spec["id"]: spec.get("default")
            for spec in catalog.get("params") or ()
            if spec.get("id") in {"steps", "cfg", "width", "height"}
        }
        rows.append(
            {
                "id": catalog["id"],
                "title": catalog.get("title") or catalog["id"],
                "summary": catalog.get("summary") or "",
                "kind": catalog.get("kind") or "other",
                "mode": catalog.get("mode"),
                "gpu": catalog["gpu"],
                "gpu_inference": catalog.get("gpu_inference") or catalog["gpu"],
                "workflow": catalog["workflow"],
                "lock": catalog["lock"],
                "io": catalog.get("io") or {},
                "defaults": defaults,
                "overlay": overlay_row,
            }
        )
    extra_ids = set(extra) - {row["id"] for row in rows}
    if extra_ids:
        raise ValueError(
            "benchmarks/models.json has ids with no catalog: " + ", ".join(sorted(extra_ids))
        )
    return rows


def fmt_seconds(value: Any) -> str:
    if value is None or value == "":
        return "—"
    number = float(value)
    if abs(number - round(number)) < 0.05:
        return f"{int(round(number))}s"
    return f"{number:.1f}s"


def fmt_gb(value: Any) -> str:
    if value is None or value == "":
        return "—"
    number = float(value)
    if abs(number - round(number)) < 0.05:
        return str(int(round(number)))
    return f"{number:.1f}"


def param_default(defaults: dict[str, Any], key: str) -> str:
    value = defaults.get(key)
    if value is None:
        return "—"
    return str(value)


def smoke_cell(overlay: dict[str, Any]) -> str:
    smoke = overlay.get("smoke") or {}
    status = str(smoke.get("status") or "pending")
    gpu = str(smoke.get("gpu") or "")
    if status == "recorded":
        warm = smoke.get("warm_seconds")
        first = fmt_seconds(smoke.get("seconds"))
        if warm is not None:
            text = f"{gpu} 首张 {first} / 热 {fmt_seconds(warm)}"
        else:
            text = f"{gpu} {first}".strip()
        return text or first
    if status == "hydrated":
        return "已 hydrate，未记时"
    return "待补测"


def _pipe(text: Any) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def render_models_markdown(overlay: dict[str, Any] | None = None) -> str:
    payload = overlay if overlay is not None else load_overlay()
    rows = merged_models(payload)
    env = payload.get("environment") or {}
    updated = payload.get("updated") or ""
    lines = [
        GENERATED_BANNER,
        "",
        "# 模型列表",
        "",
        "Studio 能跑的全部配方。**契约**在 `catalog/*.json`（标题、kind、GPU、工作流）。"
        "**权重 / 节点 / 实测**在 [`benchmarks/models.json`](https://github.com/xiaoqianran/modal-ashleykza-comfyui/blob/main/benchmarks/models.json)。"
        "加配方时先 `python3 -m recipe_scaffold <json> --id <id> --title … --kind t2i`，"
        "再手修 unresolved 锁，然后：",
        "",
        "```bash",
        "python3 -m benchmarks --write",
        "```",
        "",
        f"本页由上面这条命令生成。数据更新日期 **{updated}**。",
        "",
        "## 共用环境",
        "",
        "| 项 | 值 |",
        "|---|---|",
        f"| Image | { _pipe(env.get('image')) } |",
        f"| ComfyUI | **{_pipe(env.get('comfyui_version'))}** |",
        f"| 平台 | {_pipe(env.get('platform'))}（profile `{_pipe(env.get('modal_profile'))}`） |",
        f"| 计时 | {_pipe(env.get('measurement'))} |",
        f"| 空闲缩容 | **{env.get('scaledown_window_seconds', 5)} 秒**（leftover `modal serve` / 开着的 ComfyUI 页会挡住） |",
        "",
        "测试默认 **L40S**（FLUX.2 / TRELLIS.2 只能 RTX-PRO-6000）。正式推理 **RTX-PRO-6000**。不要用 T4。冒烟用 `modal deploy`；测完停残留容器，不要 `modal app stop`。",
        "",
        "## 总览",
        "",
        "| 配方 | 标题 | kind | 测试 GPU | 正式 GPU | 步数 | 输出 | 权重 | 实测 |",
        "|---|---|---|---|---|---:|---|---|---|",
    ]
    by_kind: dict[str, list[dict[str, Any]]] = {key: [] for key, _title in KIND_SECTIONS}
    for row in rows:
        kind = str(row["kind"] if row["kind"] in by_kind else "other")
        by_kind[kind].append(row)
        overlay_row = row["overlay"]
        weights = overlay_row.get("weights_gb")
        lines.append(
            "| `{id}` | {title} | {kind} | **{gpu}** | {inference} | {steps} | {output} | {weights} | {smoke} |".format(
                id=_pipe(row["id"]),
                title=_pipe(row["title"]),
                kind=_pipe(row["kind"]),
                gpu=_pipe(row["gpu"]),
                inference=_pipe(row["gpu_inference"]),
                steps=param_default(row["defaults"], "steps"),
                output=_pipe(overlay_row.get("output") or "—"),
                weights=f"{fmt_gb(weights)} GB" if weights is not None else "—",
                smoke=_pipe(smoke_cell(overlay_row)),
            )
        )
    lines.extend(["", "kind：`t2i` 文生图，`t2v` 文生视频，`i2v` 图生视频，`i23d` 图生 3D。", ""])
    for kind, title in KIND_SECTIONS:
        group = by_kind.get(kind) or []
        if not group:
            continue
        lines.extend([f"## {title}", ""])
        for row in group:
            overlay_row = row["overlay"]
            smoke = overlay_row.get("smoke") or {}
            shared = overlay_row.get("shared_weights_with") or []
            weights_txt = (
                f"{fmt_gb(overlay_row.get('weights_gb'))} GB"
                if overlay_row.get("weights_gb") is not None
                else "—"
            )
            vram_txt = (
                f"{fmt_gb(overlay_row.get('vram_gb'))} GB"
                if overlay_row.get("vram_gb") is not None
                else "—"
            )
            ram_bit = (
                f"；主机内存约 {fmt_gb(overlay_row.get('host_ram_gb'))} GB"
                if overlay_row.get("host_ram_gb") is not None
                else ""
            )
            lines.extend(
                [
                    f"### {row['title']} (`{row['id']}`)",
                    "",
                    row["summary"] or overlay_row.get("weights_note") or "",
                    "",
                    "| 项 | 值 |",
                    "|---|---|",
                    f"| 工作流 | `{row['workflow']}` |",
                    f"| 锁 | `{row['lock']}` |",
                    f"| 模式 | `{row['mode']}` |",
                    f"| 量化 | {_pipe(overlay_row.get('quant') or '—')} |",
                    f"| 节点 | {_pipe(overlay_row.get('nodes') or '—')} |",
                    f"| 权重 | {weights_txt}；显存 {vram_txt}{ram_bit} |",
                    f"| 共用 | {', '.join(f'`{item}`' for item in shared) if shared else '—'} |",
                    f"| 实测状态 | `{smoke.get('status')}`"
                    + (f" · {smoke.get('source')}" if smoke.get("source") else "")
                    + (f" · {smoke.get('date')}" if smoke.get("date") else "")
                    + " |",
                    f"| 实测 GPU / 耗时 | {_pipe(smoke_cell(overlay_row))} |",
                ]
            )
            if smoke.get("output"):
                lines.append(f"| 冒烟产物 | {_pipe(smoke.get('output'))} |")
            if smoke.get("note"):
                lines.append(f"| 备注 | {_pipe(smoke.get('note'))} |")
            runs = overlay_row.get("runs") or []
            if runs:
                lines.extend(["", "| 样本 | 秒 |", "|---|---:|"])
                for run in runs:
                    label = run.get("prompt") or run.get("input") or run.get("note") or "—"
                    extra = f" ({run['note']})" if run.get("note") and run.get("prompt") else ""
                    lines.append(
                        f"| {_pipe(label)}{extra} | {fmt_seconds(run.get('seconds'))} |"
                    )
            lines.append("")
    lines.extend(
        [
            "## 怎么更新",
            "",
            "1. `python3 -m recipe_scaffold <官方.json> --id <id> --title … --kind t2i --write`。",
            "2. 锁里有 `unresolved` 就手补 URL / `MODEL_DIRS`，不要写 `queue_*.py`。",
            "3. 在 `benchmarks/models.json` 加同一 `id`（或脚手架 `--write-overlay`）。",
            "4. 冒烟成功后把 `status` 改成 `recorded`，填 `gpu` / `seconds` / `source`。",
            "5. `python3 -m benchmarks --write` 重写本页和 Studio 配方表。",
            "6. 用 `modal deploy` 冒烟；队列结束即停。只有改 GPU 端 Python 才用 `modal serve`。",
            "",
            "`smoke.status`：`recorded` 已记墙钟；`hydrated` 权重在 Volume 但没排队；`pending` 还没测。",
            "",
        ]
    )
    return "\n".join(lines)


def render_studio_snippet() -> str:
    return render_studio_recipe_table(list_catalogs())


def write_studio_snippet(path: Path | None = None) -> Path:
    target = path or STUDIO_SNIPPET_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_studio_snippet(), encoding="utf-8")
    return target


def write_docs(path: Path | None = None) -> Path:
    target = path or DOCS_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_models_markdown(), encoding="utf-8")
    write_studio_snippet()
    write_workflow_exception_docs()
    write_legacy_profiles_docs()
    return target


def docs_are_current() -> bool:
    models = DOCS_PATH.read_text(encoding="utf-8") if DOCS_PATH.is_file() else ""
    snippet = (
        STUDIO_SNIPPET_PATH.read_text(encoding="utf-8") if STUDIO_SNIPPET_PATH.is_file() else ""
    )
    gates = WORKFLOW_GATES_PATH.read_text(encoding="utf-8") if WORKFLOW_GATES_PATH.is_file() else ""
    profiles = (
        LEGACY_PROFILES_PATH.read_text(encoding="utf-8") if LEGACY_PROFILES_PATH.is_file() else ""
    )
    return (
        models == render_models_markdown()
        and snippet == render_studio_snippet()
        and gates == render_workflow_exception_table()
        and profiles == render_legacy_profiles_table()
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the Studio model list docs page.")
    parser.add_argument("--write", action="store_true", help=f"write {DOCS_PATH}")
    parser.add_argument("--check", action="store_true", help="exit 1 if docs are stale")
    args = parser.parse_args(argv)
    text = render_models_markdown()
    if args.write:
        write_docs()
        print(f"wrote {DOCS_PATH}", flush=True)
        print(f"wrote {STUDIO_SNIPPET_PATH}", flush=True)
        print(f"wrote {WORKFLOW_GATES_PATH}", flush=True)
        print(f"wrote {LEGACY_PROFILES_PATH}", flush=True)
        return 0
    if args.check:
        if not docs_are_current():
            raise SystemExit("stale docs; run python3 -m benchmarks --write")
        print("ok", flush=True)
        return 0
    print(text, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
